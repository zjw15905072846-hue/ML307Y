#pragma once
/*------------------------------------------includes--------------------------------------------*/
#include <stdint.h>

/*-------------------------------------------typedef---------------------------------------------*/
/* 单调时钟端口；调用方用无符号差值处理毫秒计数回绕。 */
typedef struct
{
    void *user; /* 时钟实现方上下文。 */
    /* 返回单调毫秒计数，不把 RTC 或网络校时当作时序基准。 */
    uint32_t (*millis)(void *user);
    /* 阻塞当前调用上下文指定毫秒；不可用于需要即时响应的回调。 */
    void (*wait)(void *user, uint32_t milliseconds);
} time_if_t;

