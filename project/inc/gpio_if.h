#pragma once
/*------------------------------------------includes--------------------------------------------*/
#include <stdbool.h>
#include <stdint.h>

/*-------------------------------------------typedef---------------------------------------------*/
/* GPIO 的最小可替换端口；引脚编号由具体板级适配解释。 */
typedef struct
{
    void *user; /* 实现方持有的上下文，必须至少存活到最后一次端口调用。 */
    /* 读取失败返回 false，此时 level 无效，调用方不能推断为低电平。 */
    bool (*read)(void *user, uint32_t pin, bool *level);
    /* 写入成功才返回 true；接口不负责电平有效极性的转换。 */
    bool (*write)(void *user, uint32_t pin, bool level);
} gpio_if_t;

