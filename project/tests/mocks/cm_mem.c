/*******************************************************************************
* Function Name  : cm_malloc
* Description    : 在软件测试中模拟 SDK 内存申请
* Input          : size - 申请字节数
* Output         : 新内存块
* Return         : 指针或 NULL
* Attention      : 只链接到测试固件，不进入产品构建
*******************************************************************************/
void *cm_malloc(size_t size)
{
    return malloc(size);
}

/*******************************************************************************
* Function Name  : cm_calloc
* Description    : 在软件测试中模拟 SDK 零初始化申请
* Input          : nitems - 元素数；size - 每个元素字节数
* Output         : 零初始化内存块
* Return         : 指针或 NULL
* Attention      : 只链接到测试固件，不进入产品构建
*******************************************************************************/
void *cm_calloc(size_t nitems, size_t size)
{
    return calloc(nitems, size);
}

/*******************************************************************************
* Function Name  : cm_free
* Description    : 释放测试中模拟的 SDK 内存块
* Input          : ptr - 待释放指针
* Output         : 无
* Return         : 无
* Attention      : 必须与此文件的申请函数成对使用
*******************************************************************************/
void cm_free(void *ptr)
{
    /* 当前底包 osMemoryFreeDebug 对 NULL 触发异常，不能按 libc free(NULL) 模拟。 */
    assert(ptr != NULL);
    free(ptr);
}
