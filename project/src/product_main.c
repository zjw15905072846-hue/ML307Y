/*******************************************************************************
* Function Name  : template_board_prepare
* Description    : 构建隔离测试用的虚拟板，不访问任何硬件
* Input          : services - 产品服务
* Output         : 标记虚拟板就绪
* Return         : true
* Attention      : 新真实产品必须选择对应板实现
*******************************************************************************/
bool template_board_prepare(product_services_t *services)
{
    /* 模板产品只用于验证依赖注入链路，不申请实际板级资源。 */
    services->board.ready = true;
    return true;
}

/*******************************************************************************
* Function Name  : template_product_start
* Description    : 模板产品独立入口，仅用于验证构建和链接隔离
* Input          : services - 已注入的服务
* Output         : 一条诊断
* Return         : true - 模板入口已运行
* Attention      : 不启动报警任务、不使用报警存储或网络
*******************************************************************************/
bool template_product_start(product_services_t *services)
{
    /* 诊断回调由产品外部注入，模板不会创建业务任务。 */
    services->system.fault("template-test-started", 0);
    return true;
}
